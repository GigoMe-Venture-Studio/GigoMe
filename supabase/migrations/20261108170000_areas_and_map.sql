-- ===========================================================================
-- Job locations
-- ===========================================================================

alter table public.jobs
  add column area_id smallint references public.areas (id) on delete set null,
  add column latitude double precision,
  add column longitude double precision,
  add column show_exact_location boolean not null default true,
  add constraint jobs_coordinates_pair check ((latitude is null) = (longitude is null)),
  add constraint jobs_coordinates_in_milan check (
    latitude is null or (latitude between 45.25 and 45.70 and longitude between 8.70 and 9.60));

create index jobs_area_id_idx on public.jobs (area_id);

-- "Only show the area": the stored point becomes the area's centre (or
-- nothing), whatever was sent. Runs before the checks above.
create function public.job_location_privacy()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if not new.show_exact_location then
    if new.area_id is null then
      new.latitude := null;
      new.longitude := null;
    else
      select a.latitude, a.longitude into new.latitude, new.longitude
      from public.areas a where a.id = new.area_id;
    end if;
  end if;
  return new;
end;
$$;

create trigger job_location_privacy
  before insert or update of area_id, latitude, longitude, show_exact_location on public.jobs
  for each row execute function public.job_location_privacy();

revoke all on function public.job_location_privacy() from public, anon, authenticated;
-- Trigger only, no grants.

-- Everyone reads the location of jobs they can see; owners set it.
grant select (area_id, latitude, longitude, show_exact_location) on table public.jobs to anon, authenticated;
grant insert (area_id, latitude, longitude, show_exact_location) on table public.jobs to authenticated;
grant update (area_id, latitude, longitude, show_exact_location) on table public.jobs to authenticated;
