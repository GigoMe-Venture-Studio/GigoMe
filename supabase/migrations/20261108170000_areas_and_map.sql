-- Areas and job locations, for location search and the map.
--
--   * areas: Milan areas with an approximate centre, readable by everyone and
--     changed only in the dashboard. "Elsewhere in Milan" has no centre.
--   * jobs: area_id, latitude, longitude, show_exact_location (default true).
--     When show_exact_location is false, the database replaces whatever point
--     was sent with the area's centre (or nothing, for an area without one),
--     so a private address is never stored.
--   * Coordinates come in pairs and must lie inside the Milan metro area.


-- ===========================================================================
-- Areas
-- ===========================================================================

create table public.areas (
  id         smallint generated by default as identity primary key,
  name       text not null unique check (char_length(btrim(name)) between 1 and 60),
  latitude   double precision,
  longitude  double precision,
  sort_order smallint not null default 100,
  constraint areas_centre_pair check ((latitude is null) = (longitude is null)),
  constraint areas_centre_in_milan check (
    latitude is null or (latitude between 45.25 and 45.70 and longitude between 8.70 and 9.60))
);
alter table public.areas enable row level security;

