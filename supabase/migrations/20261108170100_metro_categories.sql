-- Metro stations, job categories and the publication date.
--
--   * metro_stations: Milan's M1–M5 stations (name, lines, coordinates) from
--     OpenStreetMap (© OpenStreetMap contributors, ODbL). Readable by everyone,
--     changed only in the dashboard. The rows come from a separate data
--     migration made by scripts/fetch-metro-stations.mjs.
--   * jobs.nearest_station_id / nearest_station_m: when a job is saved with
--     an exact location, the nearest station and the distance to it in
--     metres. Area-only jobs (show_exact_location false) get none. Set only by
--     the database.
--   * jobs.category: the industry (hospitality, retail, ...), default other.
--   * jobs.published_at: when the job was first published (for the "New"
--     badge). Set only by the database.


-- ===========================================================================
-- Metro stations
-- ===========================================================================

create table public.metro_stations (
  id        smallint generated by default as identity primary key,
  name      text not null unique check (char_length(btrim(name)) between 1 and 80),
  lines     text[] not null check (cardinality(lines) between 1 and 5 and lines <@ array['M1', 'M2', 'M3', 'M4', 'M5']),
  latitude  double precision not null check (latitude between 45.25 and 45.70),
  longitude double precision not null check (longitude between 8.70 and 9.60)
);
alter table public.metro_stations enable row level security;

revoke all on table public.metro_stations from public, anon, authenticated;
-- Read-only for everyone: no write grants and no write policies.
grant select on table public.metro_stations to anon, authenticated;

create policy "Anyone can read metro stations"
  on public.metro_stations for select
  to anon, authenticated
  using (true);


-- ===========================================================================
-- Jobs: nearest station, category, publication date
-- ===========================================================================

alter table public.jobs
  add column nearest_station_id smallint references public.metro_stations (id) on delete set null,
  add column nearest_station_m integer check (nearest_station_m >= 0),
  add column category text not null default 'other' check (category in (
    'hospitality', 'retail', 'tutoring_education', 'office_admin', 'marketing_social', 'events', 'tech', 'other')),
  add column published_at timestamptz;

-- Jobs that are live today count as published at their last review (or creation).
update public.jobs set published_at = coalesce(reviewed_at, created_at) where status = 'published';

-- The nearest station for an exact location. Named to run after
-- job_location_privacy (triggers run in name order), so a point replaced by
-- an area's centre never gets a station.
create function public.job_nearest_station()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_id smallint;
  v_m double precision;
begin
  new.nearest_station_id := null;
  new.nearest_station_m := null;
  if new.show_exact_location and new.latitude is not null then
    -- Distance on a flat projection: accurate to a few metres across Milan.
    select s.id,
           sqrt(power((s.longitude - new.longitude) * 111320 * cos(radians(new.latitude)), 2)
                + power((s.latitude - new.latitude) * 110540, 2))
      into v_id, v_m
    from public.metro_stations s
    order by 2
    limit 1;
    if v_id is not null then
      new.nearest_station_id := v_id;
      new.nearest_station_m := round(v_m)::integer;
    end if;
  end if;
  return new;
end;
$$;

create trigger job_nearest_station
  before insert or update of area_id, latitude, longitude, show_exact_location on public.jobs
  for each row execute function public.job_nearest_station();

-- First publication only: editing and republishing doesn't make a job "new".
create function public.job_published_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'published' and new.published_at is null then
    new.published_at := now();
  end if;
  return new;
end;
$$;

create trigger job_published_at
  before insert or update of status on public.jobs
  for each row execute function public.job_published_at();

revoke all on function public.job_nearest_station(), public.job_published_at() from public, anon, authenticated;
-- Triggers only, no grants.

-- Everyone reads them; owners set only the category.
grant select (nearest_station_id, nearest_station_m, category, published_at) on table public.jobs to anon, authenticated;
grant insert (category) on table public.jobs to authenticated;
grant update (category) on table public.jobs to authenticated;
